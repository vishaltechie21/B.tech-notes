document.addEventListener('DOMContentLoaded', () => {
  const yearSelector = document.getElementById('yearSelector');
  const subjectSelector = document.getElementById('subject');
  const unitSelector = document.getElementById('unit');
  const downloadBtn = document.getElementById('downloadBtn');

  yearSelector.addEventListener('change', (e) => {
    const year = e.target.value;
    subjectSelector.innerHTML = '<option value="" disabled selected>Choose Subject</option>';
    subjectSelector.disabled = false;
    yearSubjects[year].forEach(sub => {
      const option = document.createElement('option');
      option.value = sub.value;
      option.textContent = sub.text;
      subjectSelector.appendChild(option);
    });
    unitSelector.innerHTML = '<option value="" disabled selected>Please select a subject first</option>';
    unitSelector.disabled = true;
    downloadBtn.disabled = true;
  });

  subjectSelector.addEventListener('change', (e) => {
    const subject = e.target.value;
    const unitsData = notesData[subject];
    unitSelector.innerHTML = '<option value="" disabled selected>Choose Unit</option>';
    if (unitsData) {
      unitSelector.disabled = false;
      Object.keys(unitsData).sort().forEach(unit => {
        const option = document.createElement('option');
        option.value = unit;
        option.textContent = "Unit " + unit;
        unitSelector.appendChild(option);
      });
      const keys = Object.keys(unitsData);
      if (keys.length === 1) {
        unitSelector.value = keys[0];
        downloadBtn.disabled = false;
      } else {
        downloadBtn.disabled = true;
      }
    } else {
      unitSelector.innerHTML = '<option value="" disabled selected>No units available</option>';
      unitSelector.disabled = true;
      downloadBtn.disabled = true;
    }
  });

  unitSelector.addEventListener('change', () => {
    if (unitSelector.value) {
      downloadBtn.disabled = false;
    }
  });

  downloadBtn.addEventListener('click', () => {
    const subject = subjectSelector.value;
    const unit = unitSelector.value;
    if (subject && unit && notesData[subject] && notesData[subject][unit]) {
      const url = notesData[subject][unit];
      window.open(url, '_blank');
    } else {
      alert("Note link is not available!");
    }
  });

  document.getElementById('share-on-whatsapp-button')?.addEventListener('click', () => {
    const urlToShare = 'https://vishaltechie21.github.io/B.tech-notes/';
    const whatsappShareUrl = 'https://api.whatsapp.com/send?text=' + encodeURIComponent(urlToShare);
    window.open(whatsappShareUrl, '_blank');
  });

  let deferredPrompt;
  const installBtn = document.getElementById('Install');

  window.addEventListener('beforeinstallprompt', (event) => {
    event.preventDefault();
    deferredPrompt = event;
    if(installBtn) installBtn.style.display = 'inline-flex';
  });

  window.addEventListener('appinstalled', () => {
    if(installBtn) installBtn.style.display = 'none';
  });

  installBtn?.addEventListener('click', () => {
    if (deferredPrompt) {
      deferredPrompt.prompt();
      deferredPrompt.userChoice.then((choiceResult) => {
        deferredPrompt = null;
      });
    }
  });
});
